/**
 * This script normalizes LLM-generated activities by ensuring they have consistent
 * fields and formats that work with the shop-activities interface.
 */

import { storage } from '../server/storage';
import { Activity, ActivityInsert } from '../shared/schema';
import { togetherAIService } from '../server/services/together-ai';

async function normalizeActivities() {
  console.log('Starting activity normalization...');
  
  try {
    // 1. Get all activities from the database
    const activities = await storage.getActivities();
    console.log(`Found ${activities.length} total activities in the database`);
    
    // 2. Identify activities that might be missing key fields or have inconsistent formats
    const activitiesNeedingUpdate = activities.filter(activity => {
      // Check for activities likely generated by LLM but missing description
      return activity.emoji && !activity.description;
    });
    
    console.log(`Found ${activitiesNeedingUpdate.length} activities that need normalization`);
    
    // 3. Process each activity that needs updating
    for (const activity of activitiesNeedingUpdate) {
      console.log(`Normalizing activity: ${activity.name} (ID: ${activity.id})`);
      
      // Generate a description if missing, using the activity name and category
      const description = activity.description || 
        `${activity.name} - A ${activity.category.toLowerCase()} activity to enhance your life.`;
      
      // Update the activity with the normalized data
      const updatedActivity: Partial<ActivityInsert> = {
        // description field is not in ActivityInsert type, so we only update other fields
        color: activity.color || generateRandomColor(),
        priority: activity.priority || calculateDefaultPriority(activity.lifeImpact),
        emoji: activity.emoji || suggestEmojiForCategory(activity.category),
        exportToCalendar: activity.exportToCalendar !== undefined ? activity.exportToCalendar : false
      };
      
      // Update the activity in the database
      await storage.updateActivity(activity.id, updatedActivity as any);
      console.log(`Updated activity ${activity.id}: ${activity.name}`);
    }
    
    console.log('Activity normalization complete!');
  } catch (error) {
    console.error('Error during activity normalization:', error);
  }
}

// Helper function to generate a random color
function generateRandomColor(): string {
  const colors = [
    '#4CAF50', '#E91E63', '#9C27B0', '#F44336', '#673AB7', 
    '#2196F3', '#00BCD4', '#FFEB3B', '#795548', '#607D8B',
    '#FF9800', '#03A9F4', '#8BC34A', '#FF5722', '#009688'
  ];
  return colors[Math.floor(Math.random() * colors.length)];
}

// Helper function to calculate default priority based on life impact
function calculateDefaultPriority(lifeImpact: number): number {
  if (lifeImpact >= 8) return 1; // Highest priority
  if (lifeImpact >= 6) return 2;
  if (lifeImpact >= 4) return 3;
  if (lifeImpact >= 2) return 4;
  return 5; // Lowest priority
}

// Helper function to suggest an emoji based on category
function suggestEmojiForCategory(category: string): string {
  const categoryEmojis: Record<string, string> = {
    'Health & Fitness': '🏃',
    'Learning & Growth': '📚',
    'Work & Career': '💼',
    'Relationships': '👨‍👩‍👧‍👦',
    'Leisure & Recreation': '🏖️',
    'Spirituality & Mindfulness': '🧘',
    'Creativity': '🎨',
    'Service & Community': '🤝',
    'Travel & Adventure': '✈️',
    'Home & Life Management': '🏠',
    'Family & Relationships': '👪',
    'Learning & Development': '🎓',
    'Spirituality': '✨',
    'Career & Finance': '💰',
    'Health': '💪',
    'Fitness': '🏋️',
    'Community & Social': '👥',
    'Leisure': '🎮',
    'Travel': '🧳',
    'Recreation': '🚴',
    'Mindfulness': '🧠'
  };
  
  // Look for an exact category match
  if (categoryEmojis[category]) {
    return categoryEmojis[category];
  }
  
  // If no exact match, look for a partial match
  for (const [key, emoji] of Object.entries(categoryEmojis)) {
    if (category.includes(key) || key.includes(category)) {
      return emoji;
    }
  }
  
  // Default fallback emoji
  return '⭐';
}

// Run the function when file is executed
normalizeActivities().then(() => {
  console.log('Script execution completed');
}).catch(err => {
  console.error('Script execution failed:', err);
  process.exit(1);
});

export default normalizeActivities;